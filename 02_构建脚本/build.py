#!/usr/bin/env python3
"""
build.py -- one-shot builder for the payload (pristine -> payload).

Usage:
    python3 build.py --pristine <pristine_dir> --out <payload_dir>
                     [--assets <assets_dir>] [--upx <upx.exe>] [--skip-upx]

Args:
    --pristine  Directory produced by extracting the official installer, i.e.
                it contains 16.8.0.4914/ SogouExe/ $PLUGINSDIR/ $SYSDIR/ $1/
    --out       Output payload directory (created if missing).
    --assets    Build assets dir (default: assets/ next to this script). Must
                contain:
                  Components/**  (official SogouFlash + ComponentConfig.ini;
                                  ComponentConfig.ini is generated by the
                                  official installer and CANNOT be derived from
                                  the official package, so it ships with us)
                  Tools/搜狗皮肤词库工具.exe  (prebuilt GUI tool)
    --upx       Path to upx executable (default: "upx" from PATH).
    --skip-upx  Skip UPX decompression.

Steps:
    1) Lay out the payload directory tree (official file mapping, see below)
    2) UPX-decompress sgutil.dll / SogouToolkits.exe / SogouToolkitsCore.dll
    3) scrub5.py patch <payload>     (strip public host literals, skip IME core)
    4) inject.py <payload>           (inject .nblk into 5 modules)
    5) mkstubexe.py SogouCloud.exe   (replace with 1KB legal-exit stub)
    6) Copy assets (Components / Tools) and the 3 hardening ps1 to payload root

Mapping (pristine -> payload):
    16.8.0.4914/*                       -> progfiles/SogouInput/16.8.0.4914/
    SogouExe/                           -> progfiles/SogouInput/SogouExe/
    $1/SogouInput/Components/           -> progfiles/SogouInput/Components/   (then overwritten by assets)
    $PLUGINSDIR/SogouPY64.ime           -> ime_system32/SogouPY.ime
    $PLUGINSDIR/SogouTSF64.ime          -> ime_system32/SogouTSF.ime
    $PLUGINSDIR/SogouPY.ime             -> ime_syswow64/SogouPY.ime
    $PLUGINSDIR/SogouTSF.ime            -> ime_syswow64/SogouTSF.ime
    $SYSDIR/IME/SogouPY/SogouImeBroker.exe   -> ime_broker/SogouImeBroker.exe
    $SYSDIR/IME/SogouPY/SogouWin10Setup.exe  -> ime_broker/SogouWin10Setup.exe
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VER = "16.8.0.4914"

FILE_MAP = [
    (r"$PLUGINSDIR\SogouPY64.ime",   r"ime_system32\SogouPY.ime"),
    (r"$PLUGINSDIR\SogouTSF64.ime",  r"ime_system32\SogouTSF.ime"),
    (r"$PLUGINSDIR\SogouPY.ime",     r"ime_syswow64\SogouPY.ime"),
    (r"$PLUGINSDIR\SogouTSF.ime",    r"ime_syswow64\SogouTSF.ime"),
    (r"$SYSDIR\IME\SogouPY\SogouImeBroker.exe",  r"ime_broker\SogouImeBroker.exe"),
    (r"$SYSDIR\IME\SogouPY\SogouWin10Setup.exe", r"ime_broker\SogouWin10Setup.exe"),
]
DIR_MAP = [
    (VER,                         r"progfiles\SogouInput\16.8.0.4914"),
    (r"SogouExe",                 r"progfiles\SogouInput\SogouExe"),
    (r"$1\SogouInput\Components", r"progfiles\SogouInput\Components"),
]
PS1_FILES = ["ime_user_register.ps1", "offline_hardening.ps1",
             "offline_hardening_user.ps1"]
UPX_MODULES = ["sgutil.dll", "SogouToolkits.exe", "SogouToolkitsCore.dll"]
STUB_SHA256 = "2e81602cef9515b04b7e9c2a9bb8ba49de94e6528962c3d154f1e2f658914bbd"


def log(*a):
    print("[build]", *a, flush=True)


def run(args, **kw):
    log("$", " ".join(str(x) for x in args))
    subprocess.check_call(args, **kw)


def copy_tree(src, dst):
    if not os.path.isdir(src):
        raise SystemExit("missing dir: %s" % src)
    for name in os.listdir(src):
        s, d = os.path.join(src, name), os.path.join(dst, name)
        if os.path.isdir(s):
            shutil.copytree(s, d, dirs_exist_ok=True)
        else:
            shutil.copy2(s, d)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pristine", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--assets", default=os.path.join(HERE, "assets"))
    ap.add_argument("--upx", default="upx")
    ap.add_argument("--skip-upx", action="store_true")
    a = ap.parse_args()

    pri, out = os.path.abspath(a.pristine), os.path.abspath(a.out)
    if not os.path.isdir(pri):
        raise SystemExit("pristine not found: %s" % pri)
    if not os.path.isdir(a.assets):
        raise SystemExit("assets not found: %s (expected 02_构建脚本/assets)" % a.assets)

    log("pristine =", pri)
    log("out      =", out)
    log("assets   =", a.assets)

    # 1) directory mapping
    for src_rel, dst_rel in DIR_MAP:
        src, dst = os.path.join(pri, src_rel), os.path.join(out, dst_rel)
        os.makedirs(dst, exist_ok=True)
        copy_tree(src, dst)
        log("copy dir ", src_rel, "->", dst_rel)
    for src_rel, dst_rel in FILE_MAP:
        src, dst = os.path.join(pri, src_rel), os.path.join(out, dst_rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if not os.path.exists(src):
            raise SystemExit("missing file: %s" % src)
        shutil.copy2(src, dst)
        log("copy file", src_rel, "->", dst_rel)

    # 2) UPX decompress
    vd = os.path.join(out, "progfiles", "SogouInput", VER)
    if a.skip_upx:
        log("skip UPX (--skip-upx)")
    else:
        for m in UPX_MODULES:
            fp = os.path.join(vd, m)
            if not os.path.exists(fp):
                log("skip upx (missing)", m)
                continue
            try:
                run([a.upx, "-d", "-k", fp])
            except Exception as e:  # noqa: BLE001
                log("UPX failed (maybe not packed), continue:", m, e)
            bak = fp + ".~upx"
            if os.path.exists(bak):
                os.remove(bak)

    # 3) scrub
    run([sys.executable, os.path.join(HERE, "scrub5.py"), "patch", out])
    # 4) inject
    run([sys.executable, os.path.join(HERE, "inject.py"), out])
    # 5) SogouCloud stub
    run([sys.executable, os.path.join(HERE, "mkstubexe.py"),
         os.path.join(vd, "SogouCloud.exe")])

    # 6) assets: Components (overwrite) + Tools
    copy_tree(os.path.join(a.assets, "Components"),
              os.path.join(out, "progfiles", "SogouInput", "Components"))
    os.makedirs(os.path.join(out, "tools"), exist_ok=True)
    copy_tree(os.path.join(a.assets, "Tools"), os.path.join(out, "tools"))
    log("assets: Components + Tools in place")

    # 7) hardening ps1 to payload root
    for f in PS1_FILES:
        shutil.copy2(os.path.join(HERE, f), os.path.join(out, f))
    log("ps1 copied to payload root")

    # 8) self-check
    sc = os.path.join(vd, "SogouCloud.exe")
    got = sha256(sc)
    log("SogouCloud.exe =", got, os.path.getsize(sc), "bytes")
    if got != STUB_SHA256:
        raise SystemExit("SogouCloud stub hash mismatch!")
    tools_dir = os.path.join(out, "tools")
    names = os.listdir(tools_dir) if os.path.isdir(tools_dir) else []
    if names:
        t = os.path.join(tools_dir, names[0])
        log("tools/ =", names[0], sha256(t), os.path.getsize(t), "bytes")
    log('done. next: makensis /DSRC="%s" sogou16-crack-cangshui.nsi' % out)


if __name__ == "__main__":
    main()
